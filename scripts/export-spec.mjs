// Writes schemas/plot-spec-v1.schema.json and docs/SPEC.md from the chart registry, so neither can drift from the code.
//   node scripts/export-spec.mjs           write
//   node scripts/export-spec.mjs --check   fail when a file is out of date
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const { chartCatalog, plotJsonSchema, LIMITS } = await import(pathToFileURL(join(root, 'packages/core/dist/index.js')).href)

const schema = { $id: 'https://superplot.dev/schema/plot-spec-v1.json', ...plotJsonSchema() }
const esc = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
const lines = ['# Plot spec v1', '', '> Generated by `scripts/export-spec.mjs` from the chart registry. Do not edit; run `npm run docs:spec`.', '',
  'A plot is one JSON object: a `type`, the `data` rows, and the columns that map onto the chart. The same object is validated, rendered, described and turned into a JSON Schema, in every binding.', '',
  '## Limits', '', '| Limit | Value |', '|---|---|', ...Object.entries(LIMITS).map(([k, v]) => `| \`${k}\` | ${v} |`), '']
for (const c of chartCatalog()) {
  lines.push(`## \`${c.type}\` — ${c.name}`, '', c.summary, '', `**Use when:** ${c.useWhen}`, '', '| Field | Type | Required | Default | Description |', '|---|---|---|---|---|')
  for (const f of c.fields) lines.push(`| \`${f.name}\` | ${esc(f.type)} | ${f.required ? 'yes' : ''} | ${f.default === undefined ? '' : '`' + esc(JSON.stringify(f.default)) + '`'} | ${esc(f.description)} |`)
  lines.push('', '```json', JSON.stringify(c.example, null, 2).split('\n').slice(0, 40).join('\n'), '```', '')
}
const outputs = [['schemas/plot-spec-v1.schema.json', JSON.stringify(schema, null, 2) + '\n'], ['docs/SPEC.md', lines.join('\n') + '\n']]
let bad = false
for (const [rel, text] of outputs) {
  const f = join(root, rel)
  if (process.argv.includes('--check')) {
    if (!existsSync(f) || readFileSync(f, 'utf8') !== text) { console.error(`${rel} is out of date: run \`npm run docs:spec\``); bad = true }
  } else {
    mkdirSync(join(f, '..'), { recursive: true })
    writeFileSync(f, text)
    console.log(`wrote ${rel}`)
  }
}
if (bad) process.exit(1)
if (process.argv.includes('--check')) console.log('spec up to date')
